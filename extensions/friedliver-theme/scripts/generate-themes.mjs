/** `#rrggbb` with an alpha byte, e.g. a('#7cc4ff', 0x33). */
function a(hex, alpha) {
  return hex.slice(0, 7) + alpha.toString(16).padStart(2, '0');
}

/** Mix two `#rrggbb` colors; t = 0 gives `x`, t = 1 gives `y`. */
function mix(x, y, t) {
  const ch = (h, i) => parseInt(h.slice(i, i + 2), 16);
  return '#' + [1, 3, 5].map((i) => Math.round(ch(x, i) * (1 - t) + ch(y, i) * t).toString(16).padStart(2, '0')).join('');
}

