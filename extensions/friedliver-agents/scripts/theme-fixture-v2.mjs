#!/usr/bin/env node
// Writes test/fixtures/theme-friedliver-{dark,light}.css: the --vscode-* variables a webview gets in
// Design System v2's FriedLiver Dark and Light. VS Code's own defaults come from the 2026 fixture of
// the same kind (scripts/theme-fixture.mjs, read from the packaged app); every key the FriedLiver
// theme sets replaces its default, as the workbench does. The extension's contributed colours
// (friedliver.*) are v2's values until B2 moves them into package.json's defaults.
//
//   node scripts/theme-fixture-v2.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const EXT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const THEMES = path.join(EXT, '..', 'friedliver-theme', 'themes');
const FIXTURES = path.join(EXT, 'test', 'fixtures');

// The agents' own colours in v2 (COMPONENTS.md v2 §1.1), oklch in the comment.
const OWN = {
  dark: { 'friedliver-decision': '#67b0f9', 'friedliver-decisionForeground': '#191714', 'friedliver-agentClaude': '#ebaf86' /* .8 .09 55 */, 'friedliver-agentCodex': '#8bd9c9' /* .83 .08 180 */, 'friedliver-agentGemini': '#a9b6f5' /* .79 .09 275 */ },
  light: { 'friedliver-decision': '#1e6ac5', 'friedliver-decisionForeground': '#ffffff', 'friedliver-agentClaude': '#984b16' /* .5 .12 50 */, 'friedliver-agentCodex': '#037465' /* .5 .09 180 */, 'friedliver-agentGemini': '#4e59b1' /* .5 .14 275 */ },
};
const FONTS = { 'chat-font-family': "'Geist', -apple-system, BlinkMacSystemFont, sans-serif", 'font-family': "'Geist', -apple-system, BlinkMacSystemFont, sans-serif", 'editor-font-family': "'Geist Mono', Menlo, monospace" };

for (const kind of ['dark', 'light']) {
  const base = fs.readFileSync(path.join(FIXTURES, `theme-${kind}-2026.css`), 'utf8');
  const vars = new Map([...base.matchAll(/(--vscode-[\w-]+):\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()]));
  const theme = JSON.parse(fs.readFileSync(path.join(THEMES, `friedliver-${kind}-color-theme.json`), 'utf8'));
  for (const [key, value] of Object.entries(theme.colors)) vars.set(`--vscode-${key.replace(/\./g, '-')}`, value);
  for (const [key, value] of Object.entries({ ...OWN[kind], ...FONTS })) vars.set(`--vscode-${key}`, value);
  const body = [...vars].map(([k, v]) => `  ${k}: ${v};`).join('\n');
  const out = path.join(FIXTURES, `theme-friedliver-${kind}.css`);
  fs.writeFileSync(out, `/* FriedLiver ${kind === 'dark' ? 'Dark' : 'Light'} (Design System v2): generated by scripts/theme-fixture-v2.mjs over theme-${kind}-2026.css; kind ${kind}. */\n:root {\n${body}\n}\n`);
  console.log(`wrote ${path.relative(EXT, out)}`);
}
