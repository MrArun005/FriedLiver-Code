#!/usr/bin/env node
// Writes test/fixtures/theme-{dark,light}-2026.css: the --vscode-* variables a
// webview gets in the owner's theme (Dark 2026, and Light 2026 to check the
// other kind), for the UI harness (?theme=dark-2026). Reads the built-in theme
// JSON (its include chain) from an installed FriedLiver or VS Code, then adds
// the registered defaults for keys the theme leaves unset that our tokens read,
// this extension's contributed colours, and the macOS default fonts.
//
//   node scripts/theme-fixture.mjs [/Applications/FriedLiver.app]

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ext = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const app = process.argv[2] ?? '/Applications/FriedLiver.app';
const themes = path.join(app, 'Contents/Resources/app/extensions/theme-defaults/themes');
const pkg = JSON.parse(fs.readFileSync(path.join(ext, 'package.json'), 'utf8'));

const read = (file) => JSON.parse(fs.readFileSync(path.join(themes, file), 'utf8').replace(/^\s*\/\/.*$/gm, '').replace(/,(\s*[}\]])/g, '$1'));

function colors(file) {
  const theme = read(file);
  const base = theme.include ? colors(path.basename(theme.include)) : {};
  return { ...base, ...theme.colors };
}

// VS Code's registered defaults (src/vs/platform/theme/common/colors/*) for keys our tokens read
// that the 2026 themes don't set: each falls back to another key or a fixed value per kind.
const REGISTERED = {
  'inlineChatInput.border': (c) => c['editorWidget.border'],
  'toolbar.hoverBackground': (c, kind) => c['toolbar.hoverBackground'] ?? (kind === 'dark' ? '#5A5D5E50' : '#B8B8B850'),
};

const FONTS = {
  // The workbench's macOS defaults, which a webview gets as these variables.
  'chat-font-family': '-apple-system, BlinkMacSystemFont, sans-serif',
  'chat-font-size': '13px',
  'font-family': '-apple-system, BlinkMacSystemFont, sans-serif',
  'font-size': '13px',
  'font-weight': 'normal',
  'editor-font-family': 'Menlo, Monaco, "Courier New", monospace',
  'editor-font-size': '12px',
};

for (const [name, file, kind] of [['dark-2026', '2026-dark.json', 'dark'], ['light-2026', '2026-light.json', 'light']]) {
  const c = colors(file);
  for (const [key, value] of Object.entries(REGISTERED)) c[key] ??= value(c, kind);
  for (const contributed of pkg.contributes.colors) c[contributed.id] ??= contributed.defaults[kind];
  const vars = Object.entries(c)
    .filter(([, v]) => typeof v === 'string' && v)
    .map(([k, v]) => `  --vscode-${k.replace(/\./g, '-')}: ${v};`);
  for (const [k, v] of Object.entries(FONTS)) vars.push(`  --vscode-${k}: ${v};`);
  const out = path.join(ext, 'test/fixtures', `theme-${name}.css`);
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, `/* ${read(file).name}: generated by scripts/theme-fixture.mjs from ${file}; kind ${kind}. */\n:root {\n${vars.join('\n')}\n}\n`);
  console.log(`${path.relative(ext, out)}: ${vars.length} variables`);
}
