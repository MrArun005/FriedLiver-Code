// The design system's tokens for the workbench: one source of numbers for the webviews and the
// workbench. Reads the Agents extension's media/tokens.css (spec: COMPONENTS.md §1) and rewrites it
// for the workbench document:
//   - every token the file defines is prefixed, --x -> --fl-x, so nothing collides with upstream's
//     own unprefixed variables (references to undefined names, e.g. --vscode-*, are left alone);
//   - :root -> .monaco-workbench, body.vscode-light -> .monaco-workbench.vs,
//     body.vscode-dark -> .monaco-workbench.vs-dark, body.vscode-high-contrast -> .monaco-workbench.hc-black,
//     body[data-platform=windows|linux] -> .monaco-workbench.windows|.linux (the v2 platform layer),
//     body.vscode-high-contrast-light -> .monaco-workbench.hc-light;
//   - width media queries (webview layout, e.g. the chat gutter) are dropped; preference queries stay.
// prepare.mjs writes the result into the upstream tree as src/vs/workbench/browser/media/friedliver-tokens.css.

import fs from 'node:fs';
import path from 'node:path';
import { ROOT_DIR } from './lib.mjs';

export const TOKENS_SOURCE = path.join(ROOT_DIR, 'extensions', 'friedliver-agents', 'media', 'tokens.css');

const SELECTORS = [
	[/:root\b/g, '.monaco-workbench'],
	[/body\.vscode-high-contrast-light\b/g, '.monaco-workbench.hc-light'],
	[/body\.vscode-high-contrast\b/g, '.monaco-workbench.hc-black'],
	[/body\.vscode-light\b/g, '.monaco-workbench.vs'],
	[/body\.vscode-dark\b/g, '.monaco-workbench.vs-dark'],
	[/body\[data-platform='windows'\]/g, '.monaco-workbench.windows'],
	[/body\[data-platform='linux'\]/g, '.monaco-workbench.linux'],
];

/** Splits CSS into top-level chunks: [prelude, body] for rules and at-rules, comments dropped. */
function topLevel(css) {
	const text = css.replace(/\/\*[\s\S]*?\*\//g, '');
	const out = [];
	let depth = 0;
	let start = 0;
	let open = -1;
	for (let i = 0; i < text.length; i++) {
		if (text[i] === '{') {
			if (depth++ === 0) open = i;
		} else if (text[i] === '}') {
			if (--depth === 0) {
				out.push([text.slice(start, open).trim(), text.slice(open + 1, i)]);
				start = i + 1;
			}
		}
	}
	return out;
}

/** The workbench copy of tokens.css. Throws if the source has no :root tokens. */
export function workbenchTokens(source) {
	const defined = new Set([...source.matchAll(/(?:^|[;{\s])(--[\w-]+)\s*:/g)].map((m) => m[1]));
	if (!defined.size) throw new Error('tokens.css defines no tokens');
	const rename = (s) => s.replace(/--[\w-]+/g, (name) => (defined.has(name) ? `--fl-${name.slice(2)}` : name));
	const mapSelectors = (s) => SELECTORS.reduce((acc, [re, to]) => acc.replace(re, to), s);
	const rules = [];
	for (const [prelude, body] of topLevel(source)) {
		if (/^@media\b/.test(prelude)) {
			if (/\b(?:max|min)-width\b/.test(prelude)) continue; // webview layout only
			const inner = topLevel(body).map(([p, b]) => `\t${mapSelectors(p)} {${rename(b).replace(/\n/g, '\n\t')}}`).join('\n');
			rules.push(`${prelude} {\n${inner}\n}`);
		} else if (prelude.startsWith('@')) {
			continue; // keyframes and the like belong to the webviews
		} else {
			rules.push(`${mapSelectors(prelude)} {${rename(body)}}`);
		}
	}
	if (!rules.some((r) => r.startsWith('.monaco-workbench {'))) throw new Error('tokens.css has no :root block');
	return [
		'/* Generated by scripts/workbench-tokens.mjs from extensions/friedliver-agents/media/tokens.css. Do not edit. */',
		...rules,
		'',
	].join('\n');
}

/** Token names (with the --fl- prefix) the generated CSS defines. */
export function definedTokens(generated) {
	return new Set([...generated.matchAll(/(--fl-[\w-]+)\s*:/g)].map((m) => m[1]));
}

export function readTokensSource() {
	if (!fs.existsSync(TOKENS_SOURCE)) {
		throw new Error(`${path.relative(ROOT_DIR, TOKENS_SOURCE)} is missing: the workbench tokens come from the design system (ds/components)`);
	}
	return fs.readFileSync(TOKENS_SOURCE, 'utf8').replace(/\r\n/g, '\n');
}
