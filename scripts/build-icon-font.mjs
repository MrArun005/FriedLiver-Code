#!/usr/bin/env node
// FriedLiver's icons from one source, extensions/friedliver-theme/icons/glyphs.json (COMPONENTS.md §1.6, §6.3, §6.21):
//   - the FriedLiver Icons product icon theme: the strokes outlined at 1.5px into friedliver-icons.woff2
//     (scripts/icon-font.py: skia-pathops + fontTools, hash-locked in scripts/icon-font-requirements.txt)
//     and friedliver-icons.json (id -> codepoint, in glyphs.json order from U+E000);
//   - the FriedLiver Files file-icon theme: one SVG per glyph in --fg-2 for dark and light themes, and friedliver-files.json.
//
//   node scripts/build-icon-font.mjs           write them
//   node scripts/build-icon-font.mjs --check   exit 1 if any committed output is stale (CI)
//
// PYTHON (default python3) must have the requirements installed.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
export const ICONS = path.join(ROOT, 'extensions', 'friedliver-theme', 'icons');
export const FIRST_CODEPOINT = 0xe000;
/** --fg-2 in FriedLiver Dark and Light (COMPONENTS.md §1.1). */
export const FILE_COLORS = { dark: '#aca8a5', light: '#5e5c59' };

/** Which file glyph each extension or name gets. Language is not colour-coded: only the shape changes. */
const CODE = ['ts', 'tsx', 'mts', 'cts', 'js', 'jsx', 'mjs', 'cjs', 'py', 'go', 'rs', 'java', 'kt', 'c', 'h', 'cc', 'cpp', 'hpp', 'cs', 'rb', 'php', 'swift', 'm', 'scala', 'dart', 'lua', 'sh', 'bash', 'zsh', 'fish', 'ps1', 'bat', 'css', 'scss', 'less', 'html', 'vue', 'svelte', 'astro', 'sql', 'graphql', 'zig', 'ex', 'exs', 'hs', 'ml', 'r', 'pl', 'xml'];
const EXTENSIONS = {
  ...Object.fromEntries(CODE.map((e) => [e, 'code'])),
  ...Object.fromEntries(['json', 'jsonc', 'json5', 'jsonl'].map((e) => [e, 'json'])),
  ...Object.fromEntries(['md', 'mdx', 'markdown', 'txt', 'rst'].map((e) => [e, 'markdown'])),
  ...Object.fromEntries(['png', 'jpg', 'jpeg', 'gif', 'svg', 'webp', 'ico', 'avif', 'bmp'].map((e) => [e, 'image'])),
  ...Object.fromEntries(['yml', 'yaml', 'toml', 'ini', 'cfg', 'conf', 'env', 'properties'].map((e) => [e, 'config'])),
  lock: 'lock',
  ...Object.fromEntries(['ts', 'tsx', 'js', 'jsx', 'mjs', 'py', 'go', 'rs'].flatMap((e) => [[`test.${e}`, 'test'], [`spec.${e}`, 'test']])),
};
const NAMES = {
  ...Object.fromEntries(['package-lock.json', 'yarn.lock', 'pnpm-lock.yaml', 'bun.lockb', 'Cargo.lock', 'poetry.lock', 'Gemfile.lock', 'go.sum'].map((n) => [n, 'lock'])),
  ...Object.fromEntries(['.gitignore', '.gitattributes', '.editorconfig', '.npmrc', '.nvmrc', '.prettierrc', '.eslintrc', '.env', '.dockerignore', 'Dockerfile', 'Makefile'].map((n) => [n, 'config'])),
  ...Object.fromEntries(['README', 'LICENSE', 'CHANGELOG'].map((n) => [n, 'markdown'])),
};

export function readGlyphs() {
  return JSON.parse(fs.readFileSync(path.join(ICONS, 'glyphs.json'), 'utf8'));
}

const json = (v) => JSON.stringify(v, null, 2) + '\n';

/** Every output file, path relative to ICONS -> contents. */
export function outputs(src, buildFont) {
  const out = {};
  const ids = Object.keys(src.product);
  out['friedliver-icons.json'] = json({
    $comment: 'Generated by scripts/build-icon-font.mjs from glyphs.json. Do not edit.',
    fonts: [{ id: 'friedliver-icons', src: [{ path: './friedliver-icons.woff2', format: 'woff2' }], weight: 'normal', style: 'normal' }],
    iconDefinitions: Object.fromEntries(ids.map((id, i) => [id, { fontCharacter: `\\${(FIRST_CODEPOINT + i).toString(16).toUpperCase()}` }])),
  });
  out['friedliver-icons.woff2'] = buildFont(ids.map((id, i) => ({ name: id, codepoint: FIRST_CODEPOINT + i, ...src.product[id] })), src);

  for (const [name, d] of Object.entries(src.files)) {
    for (const [variant, color] of Object.entries(FILE_COLORS)) {
      out[`files/${name}${variant === 'light' ? '-light' : ''}.svg`] =
        `<svg xmlns="http://www.w3.org/2000/svg" width="16" height="16" viewBox="0 0 16 16" fill="none" stroke="${color}" stroke-width="${src.stroke}" stroke-linecap="round" stroke-linejoin="round"><path d="${d}"/></svg>\n`;
    }
  }
  const theme = (suffix) => ({
    file: `_file${suffix}`,
    folder: `_folder${suffix}`,
    folderExpanded: `_folder-open${suffix}`,
    rootFolder: `_folder${suffix}`,
    rootFolderExpanded: `_folder-open${suffix}`,
    fileExtensions: Object.fromEntries(Object.entries(EXTENSIONS).map(([e, g]) => [e, `_${g}${suffix}`])),
    fileNames: Object.fromEntries(Object.entries(NAMES).map(([n, g]) => [n, `_${g}${suffix}`])),
  });
  out['friedliver-files.json'] = json({
    $comment: 'Generated by scripts/build-icon-font.mjs from glyphs.json. Do not edit.',
    hidesExplorerArrows: false,
    iconDefinitions: Object.fromEntries(Object.keys(src.files).flatMap((n) => [
      [`_${n}`, { iconPath: `./files/${n}.svg` }],
      [`_${n}-light`, { iconPath: `./files/${n}-light.svg` }],
    ])),
    ...theme(''),
    light: theme('-light'),
  });
  return out;
}

function pythonFont(glyphs, src) {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'fl-icons-'));
  try {
    const file = path.join(tmp, 'icons.woff2');
    execFileSync(process.env.PYTHON || 'python3', ['-I', path.join(ROOT, 'scripts', 'icon-font.py'), file], {
      input: JSON.stringify({ grid: src.grid, stroke: src.stroke, glyphs }),
      stdio: ['pipe', 'inherit', 'inherit'],
    });
    return fs.readFileSync(file);
  } finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const want = outputs(readGlyphs(), pythonFont);
  const stale = [];
  for (const [rel, contents] of Object.entries(want)) {
    const file = path.join(ICONS, rel);
    const same = fs.existsSync(file) && Buffer.compare(fs.readFileSync(file), Buffer.from(contents)) === 0;
    if (same) continue;
    if (check) stale.push(rel);
    else {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, contents);
    }
  }
  // Files no glyph produces any more.
  const have = fs.readdirSync(path.join(ICONS, 'files')).map((f) => `files/${f}`);
  for (const rel of have.filter((r) => !(r in want))) {
    if (check) stale.push(`${rel} (no longer generated)`);
    else fs.rmSync(path.join(ICONS, rel));
  }
  if (stale.length) {
    console.error(`stale: ${stale.join(', ')}\nRun: node scripts/build-icon-font.mjs`);
    process.exit(1);
  }
  console.log(check ? 'icons are up to date' : `wrote ${Object.keys(want).length} files to ${path.relative(ROOT, ICONS)}`);
}
